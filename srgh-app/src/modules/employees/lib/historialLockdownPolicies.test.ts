const readMigration = (file: string) => readFileSync(resolve('supabase/migrations', file), 'utf8')

function extractFunction(file: string, fullName: string) {
  const escaped = fullName.replace('.', '\\.')
  const match = readMigration(file).match(
    new RegExp(`CREATE OR REPLACE FUNCTION ${escaped}\\([\\s\\S]*?\\$\\$[\\s\\S]*?\\$\\$[^;]*;`)
  )
  if (!match) throw new Error(`Missing function ${fullName} in ${file}`)
  return match[0]
}

