import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { PGlite } from '@electric-sql/pglite'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'

const sql = readFileSync(
  resolve('supabase/migrations/20261106181220_biometria_permission_rollout.sql'),
  'utf8'
)
let db: PGlite

describe('biometry permission rollout', () => {
  beforeEach(async () => {
    db = new PGlite()
    await db.exec(`
      CREATE TABLE sgrh_cat_roles (rol_id int PRIMARY KEY, rol_codigo text UNIQUE);
      CREATE TABLE sgrh_cat_permisos (
        per_id int GENERATED BY DEFAULT AS IDENTITY (START WITH 2000) PRIMARY KEY,
        per_codigo text UNIQUE, per_modulo text, per_nombre text, per_descripcion text
      );
      CREATE TABLE sgrh_rol_permisos (
        rpe_id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        rpe_rol_id int REFERENCES sgrh_cat_roles(rol_id),
        rpe_permiso_id int REFERENCES sgrh_cat_permisos(per_id)
      );
      INSERT INTO sgrh_cat_roles VALUES
        (11,'ADMIN'),(23,'GERENTE'),(35,'RRHH'),(47,'SUPERVISOR'),
        (59,'JEFE_SUCURSAL'),(71,'SUPERADMIN'),(83,'KIOSCO'),(95,'EMPLEADO');
    `)
  }, 30000)
  afterEach(async () => {
    await db?.close()
  })

  it('crea el permiso y resuelve los roles por código sin ejecutar seeds', async () => {
    await db.exec(sql)
    const result = await db.query<{ rol_codigo: string }>(`
      SELECT r.rol_codigo FROM sgrh_rol_permisos rp
      JOIN sgrh_cat_roles r ON r.rol_id=rp.rpe_rol_id
      JOIN sgrh_cat_permisos p ON p.per_id=rp.rpe_permiso_id
      WHERE p.per_codigo='BIOMETRIA_WRITE' ORDER BY r.rol_codigo
    `)
    expect(result.rows.map((r) => r.rol_codigo)).toEqual([
      'ADMIN',
      'GERENTE',
      'JEFE_SUCURSAL',
      'RRHH',
      'SUPERADMIN',
      'SUPERVISOR',
    ])
  })

  it('es repetible y conserva IDs, permisos y asignaciones anteriores', async () => {
    await db.exec(`
      INSERT INTO sgrh_cat_permisos VALUES (73,'BIOMETRIA_WRITE','custom','Existing','Preserve');
      INSERT INTO sgrh_cat_permisos VALUES (99,'OTHER_PERMISSION','custom','Other','Preserve');
      INSERT INTO sgrh_rol_permisos (rpe_rol_id,rpe_permiso_id) VALUES (11,73),(83,99);
    `)
    await db.exec(sql)
    await db.exec(sql)
    const permission = await db.query(
      "SELECT per_id,per_nombre FROM sgrh_cat_permisos WHERE per_codigo='BIOMETRIA_WRITE'"
    )
    expect(permission.rows).toEqual([{ per_id: 73, per_nombre: 'Existing' }])
    const count = await db.query<{ count: number }>(
      'SELECT count(*)::int count FROM sgrh_rol_permisos'
    )
    expect(count.rows[0].count).toBe(7)
    const other = await db.query(
      'SELECT rpe_rol_id,rpe_permiso_id FROM sgrh_rol_permisos WHERE rpe_permiso_id=99'
    )
    expect(other.rows).toEqual([{ rpe_rol_id: 83, rpe_permiso_id: 99 }])
  })

  it('no recrea SUPERADMIN donde el rol retirado ya no existe', async () => {
    await db.exec("DELETE FROM sgrh_cat_roles WHERE rol_codigo='SUPERADMIN'")
    await db.exec(sql)
    const result = await db.query<{ count: number }>(
      'SELECT count(*)::int count FROM sgrh_rol_permisos'
    )
    expect(result.rows[0].count).toBe(5)
    const role = await db.query("SELECT rol_id FROM sgrh_cat_roles WHERE rol_codigo='SUPERADMIN'")
    expect(role.rows).toEqual([])
  })
})
