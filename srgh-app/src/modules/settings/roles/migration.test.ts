import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { PGlite } from '@electric-sql/pglite'
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it } from 'vitest'

/**
 * Las RPC de roles contra un Postgres real (PGlite): toda la seguridad de este
 * módulo vive en SQL y los tests de las acciones la mockean.
 *
 * Se aplican las cinco migraciones de roles EN ORDEN. Entre la tercera y la
 * cuarta se crean, con las RPC viejas, un rol limitado a una sucursal y una
 * «versión» de un rol para una sucursal: así la cuarta (roles por empresa) y
 * la quinta (roles sin sucursal) se prueban sobre datos como los de un
 * proyecto que ya tenía la rama aplicada, y se ve qué pasa con esos roles
 * cuando dejan de atarse a una sucursal.
 */

const A1 = '00000000-0000-4000-8000-000000000001' // Administrador, empresa 1
const A2 = '00000000-0000-4000-8000-000000000002' // Administrador, empresa 2
const G1 = '00000000-0000-4000-8000-000000000003' // Gerente de Centro, empresa 1
const L1 = '00000000-0000-4000-8000-000000000008' // empresa 1, rol recortado (lo arma cada test)

const MIGRACIONES = [
  '20261109031500_roles_por_empresa.sql',
  '20261109050000_roles_personalizar_sucursal.sql',
  '20261109060000_roles_sistema_editables.sql',
]
/** Las que se prueban, sobre los datos que dejaron las anteriores. */
const NUEVAS = [
  '20261110050239_roles_por_empresa_copias.sql',
  '20261110080629_roles_sin_sucursal.sql',
]

let db: PGlite

const sql = (file: string) => readFileSync(resolve('supabase/migrations', file), 'utf8')

async function one<T>(query: string, params: unknown[] = []): Promise<T> {
  return (await db.query<{ r: T }>(query, params)).rows[0].r
}

const save = (
  actor: string,
  empresa: number,
  id: number | null,
  nombre: string,
  permisos: string[]
) =>
  one<number>('SELECT sgrh_save_role($1::uuid,$2,$3,$4,null,$5::text[]) r', [
    actor,
    empresa,
    id,
    nombre,
    permisos,
  ])

const remove = (actor: string, empresa: number, id: number) =>
  one<string>('SELECT sgrh_delete_role($1::uuid,$2,$3) r', [actor, empresa, id])

const rolId = (codigo: string) =>
  one<number>('SELECT rol_id r FROM sgrh_cat_roles WHERE rol_codigo=$1', [codigo])

const permisos = (rol: number) =>
  one<string[]>(
    `SELECT coalesce(array_agg(p.per_codigo ORDER BY p.per_codigo),'{}') r
     FROM sgrh_rol_permisos rp JOIN sgrh_cat_permisos p ON p.per_id=rp.rpe_permiso_id WHERE rpe_rol_id=$1`,
    [rol]
  )

const rolDe = (usuario: number) =>
  one<number>(
    'SELECT uer_rol_id r FROM sgrh_usuarios_empresa_rol WHERE uer_usuario_id=$1 AND uer_activo ORDER BY uer_id LIMIT 1',
    [usuario]
  )

const asignar = (
  usuario: number,
  empresa: number,
  sucursal: number | null,
  rol: number,
  activo = true
) =>
  db.query(
    'INSERT INTO sgrh_usuarios_empresa_rol(uer_usuario_id,uer_empresa_id,uer_sucursal_id,uer_rol_id,uer_activo) VALUES($1,$2,$3,$4,$5)',
    [usuario, empresa, sucursal, rol, activo]
  )

/** El rechazo deja la transacción del test usable (savepoint) y compara mensaje y código. */
async function rejects(p: () => Promise<unknown>, mensaje: RegExp, code?: string) {
  await db.exec('SAVEPOINT intento')
  try {
    await p()
  } catch (e) {
    await db.exec('ROLLBACK TO SAVEPOINT intento')
    const err = e as { message: string; code?: string }
    expect(err.message).toMatch(mensaje)
    if (code) expect(err.code).toBe(code)
    return
  }
  await db.exec('RELEASE SAVEPOINT intento')
  throw new Error(`Se esperaba un rechazo: ${mensaje}`)
}

/** Rol con solo los permisos dados para L1 (empresa 1). */
async function actorRecortado(perms: string[]) {
  const id = await save(A1, 1, null, 'Recortado', perms)
  await asignar(8, 1, null, id)
  return id
}

describe('SGRH-108 · roles por empresa (migraciones reales)', () => {
  // Creados con las RPC viejas, antes de la migración que desata los roles de las sucursales.
  let versionCentro: number
  let soloNorte: number

  beforeAll(async () => {
    db = new PGlite()
    await db.exec(`
      CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE TABLE sgrh_empresas(org_id int PRIMARY KEY);
      CREATE TABLE sgrh_sucursales(suc_id int PRIMARY KEY, suc_empresa_id int REFERENCES sgrh_empresas, suc_nombre text, suc_activa boolean DEFAULT true);
      CREATE TABLE sgrh_usuarios(usr_id int PRIMARY KEY, usr_auth_id uuid UNIQUE, usr_activo boolean DEFAULT true);
      CREATE TABLE sgrh_cat_roles(rol_id int GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
        rol_codigo text NOT NULL UNIQUE, rol_nombre text, rol_descripcion text, rol_activo boolean DEFAULT true);
      CREATE TABLE sgrh_cat_permisos(per_id int PRIMARY KEY, per_codigo text UNIQUE);
      CREATE TABLE sgrh_rol_permisos(rpe_id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        rpe_rol_id int REFERENCES sgrh_cat_roles, rpe_permiso_id int REFERENCES sgrh_cat_permisos);
      CREATE TABLE sgrh_usuarios_empresa_rol(uer_id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, uer_usuario_id int,
        uer_empresa_id int, uer_sucursal_id int, uer_rol_id int REFERENCES sgrh_cat_roles, uer_activo boolean DEFAULT true);
      CREATE TABLE sgrh_config_auditoria(aud_id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, aud_empresa_id int,
        aud_usuario_id int, aud_entidad text, aud_referencia text, aud_accion text);
      CREATE FUNCTION get_empresa_id() RETURNS int LANGUAGE sql AS 'SELECT 1';

      INSERT INTO sgrh_empresas VALUES (1),(2);
      INSERT INTO sgrh_sucursales VALUES (10,1,'Centro',true),(20,1,'Norte',true),(30,2,'Ajena',true);
      INSERT INTO sgrh_usuarios(usr_id,usr_auth_id) VALUES
        (1,'${A1}'),(2,'${A2}'),(3,'${G1}'),(4,gen_random_uuid()),(5,gen_random_uuid()),
        (6,gen_random_uuid()),(7,gen_random_uuid()),(8,'${L1}'),(9,gen_random_uuid());
      INSERT INTO sgrh_cat_permisos VALUES
        (1,'ROLES_WRITE'),(2,'NOMINA_READ'),(3,'NOMINA_WRITE'),(4,'EMPLEADOS_READ'),
        (5,'ASISTENCIA_KIOSCO'),(6,'USUARIOS_WRITE'),(7,'MI_HORARIO_READ'),(8,'EMPLEADOS_WRITE');
      -- Plantillas: tres activas, dos inactivas y el kiosco.
      INSERT INTO sgrh_cat_roles(rol_id,rol_codigo,rol_nombre,rol_activo) VALUES
        (2,'ADMIN','Administrador de Empresa',true),(4,'GERENTE','Gerente de Sucursal',true),
        (8,'EMPLEADO','Empleado',true),(3,'RRHH','Recursos Humanos',false),
        (6,'CONTADOR','Contador',false),(13,'KIOSCO','Kiosco de asistencia',false);
      INSERT INTO sgrh_rol_permisos(rpe_rol_id,rpe_permiso_id) VALUES
        (2,1),(2,2),(2,3),(2,4),(2,6),(2,8),(4,4),(4,2),(8,7),(3,2),(3,3),(3,4),(6,2),(13,5);
      INSERT INTO sgrh_usuarios_empresa_rol(uer_usuario_id,uer_empresa_id,uer_sucursal_id,uer_rol_id,uer_activo) VALUES
        (1,1,null,2,true),   -- admin empresa 1
        (2,2,null,2,true),   -- admin empresa 2
        (3,1,10,4,true),     -- gerente solo en Centro
        (4,1,20,4,true),     -- gerente solo en Norte
        (5,1,10,13,true),    -- kiosco de Centro
        (6,2,30,6,false),    -- contador histórico de la empresa 2
        (7,1,10,4,true),(7,1,20,4,true); -- gerente en dos sucursales
    `)
    for (const file of MIGRACIONES) await db.exec(sql(file))
    // Con las RPC viejas (la de guardar todavía recibía la sucursal):
    // la versión de «Gerente» para Centro, que se lleva al usuario 3...
    versionCentro = (
      await one<{ id: number }>('SELECT sgrh_customize_role_for_branch($1::uuid,1,4,10) r', [A1])
    ).id
    await db.query(
      `DELETE FROM sgrh_rol_permisos WHERE rpe_rol_id=$1
       AND rpe_permiso_id=(SELECT per_id FROM sgrh_cat_permisos WHERE per_codigo='NOMINA_READ')`,
      [versionCentro]
    )
    // ...y un rol limitado a Norte, con una cuenta de esa tienda.
    soloNorte = await one<number>(
      `SELECT sgrh_save_role($1::uuid,1,null,'Cajero Norte',null,20,ARRAY['EMPLEADOS_READ']) r`,
      [A1]
    )
    await asignar(9, 1, 20, soloNorte)
    for (const file of NUEVAS) await db.exec(sql(file))
  }, 30000)

  beforeEach(async () => {
    await db.exec('BEGIN')
  })
  afterEach(async () => {
    await db.exec('ROLLBACK')
  })
  afterAll(async () => {
    await db?.close()
  })

  describe('instanciación', () => {
    it('cada empresa recibe copias de las plantillas que usa, con sus permisos', async () => {
      const codigos = async (empresa: number) =>
        (
          await db.query<{ rol_codigo: string }>(
            `SELECT rol_codigo FROM sgrh_cat_roles WHERE rol_empresa_id=$1
             AND rol_codigo !~ '^EMPRESA_[0-9]+_[0-9]+$' ORDER BY rol_codigo`,
            [empresa]
          )
        ).rows.map((r) => r.rol_codigo)
      expect(await codigos(1)).toEqual([
        'EMPRESA_1_ADMIN',
        'EMPRESA_1_EMPLEADO',
        'EMPRESA_1_GERENTE',
      ])
      // CONTADOR está inactivo pero la empresa 2 lo usó: también se copia.
      expect(await codigos(2)).toEqual([
        'EMPRESA_2_ADMIN',
        'EMPRESA_2_CONTADOR',
        'EMPRESA_2_EMPLEADO',
        'EMPRESA_2_GERENTE',
      ])
      expect(await permisos(await rolId('EMPRESA_1_GERENTE'))).toEqual(await permisos(4))
      expect(
        await one('SELECT rol_nombre r FROM sgrh_cat_roles WHERE rol_codigo=$1', [
          'EMPRESA_1_GERENTE',
        ])
      ).toBe('Gerente de Sucursal')
    })

    it('las cuentas pasan a la copia de su empresa; el kiosco se queda en el del sistema', async () => {
      expect(await rolDe(1)).toBe(await rolId('EMPRESA_1_ADMIN'))
      expect(await rolDe(2)).toBe(await rolId('EMPRESA_2_ADMIN'))
      expect(await rolDe(4)).toBe(await rolId('EMPRESA_1_GERENTE'))
      expect(
        await one('SELECT uer_rol_id r FROM sgrh_usuarios_empresa_rol WHERE uer_usuario_id=6', [])
      ).toBe(await rolId('EMPRESA_2_CONTADOR'))
      expect(await rolDe(5)).toBe(13)
      // Ninguna asignación queda en una plantilla salvo el kiosco.
      expect(
        await one(
          `SELECT count(*)::int r FROM sgrh_usuarios_empresa_rol a JOIN sgrh_cat_roles c ON c.rol_id=a.uer_rol_id
         WHERE c.rol_empresa_id IS NULL AND c.rol_codigo <> 'KIOSCO'`
        )
      ).toBe(0)
    })

    it('es re-ejecutable: no duplica roles ni permisos', async () => {
      const roles = await one<number>('SELECT count(*)::int r FROM sgrh_cat_roles')
      const filas = await one<number>('SELECT count(*)::int r FROM sgrh_rol_permisos')
      expect(await one('SELECT sgrh_private.instanciar_roles_empresa(1) r')).toBe(0)
      expect(await one('SELECT count(*)::int r FROM sgrh_cat_roles')).toBe(roles)
      expect(await one('SELECT count(*)::int r FROM sgrh_rol_permisos')).toBe(filas)
    })

    it('si la empresa ya tiene un rol con el nombre de la plantilla, la copia lleva una marca', async () => {
      // La empresa 1 no usaba RRHH (inactiva): crea un rol propio con ese nombre
      // y después aparece una asignación histórica a la plantilla.
      const propio = await save(A1, 1, null, 'Recursos Humanos', [])
      await asignar(8, 1, null, 3, false)
      expect(await one('SELECT sgrh_private.instanciar_roles_empresa(1) r')).toBe(1)
      const copia = await rolId('EMPRESA_1_RRHH')
      expect(copia).not.toBe(propio)
      expect(await one('SELECT rol_nombre r FROM sgrh_cat_roles WHERE rol_id=$1', [copia])).toBe(
        'Recursos Humanos (original)'
      )
      expect(await permisos(copia)).toEqual(await permisos(3))
      expect(
        await one('SELECT uer_rol_id r FROM sgrh_usuarios_empresa_rol WHERE uer_usuario_id=8')
      ).toBe(copia)
    })
  })

  describe('los roles ya no se atan a una sucursal', () => {
    it('la tabla pierde las columnas de sucursal y de versión, y la RPC que creaba versiones', async () => {
      expect(
        await one(
          `SELECT count(*)::int r FROM information_schema.columns
           WHERE table_name='sgrh_cat_roles' AND column_name IN ('rol_sucursal_id','rol_base_id')`
        )
      ).toBe(0)
      expect(
        await one(
          `SELECT count(*)::int r FROM pg_proc WHERE proname='sgrh_customize_role_for_branch'`
        )
      ).toBe(0)
      // Una sola sgrh_save_role: la de la firma vieja (con sucursal) no queda al lado.
      expect(await one(`SELECT count(*)::int r FROM pg_proc WHERE proname='sgrh_save_role'`)).toBe(
        1
      )
    })

    it('la versión que existía queda como un rol común: conserva su cuenta y sus permisos', async () => {
      expect(
        await one('SELECT rol_activo AND rol_empresa_id=1 r FROM sgrh_cat_roles WHERE rol_id=$1', [
          versionCentro,
        ])
      ).toBe(true)
      // Nadie cambia de permisos por la migración: la cuenta sigue donde estaba,
      // con lo que la versión tenía (se le había quitado NOMINA_READ).
      expect(await rolDe(3)).toBe(versionCentro)
      expect(await permisos(versionCentro)).toEqual(['EMPLEADOS_READ'])
      // Y se edita y se le asignan cuentas de cualquier tienda, como a cualquier rol.
      await save(A1, 1, versionCentro, 'Gerente de Centro', ['EMPLEADOS_READ', 'NOMINA_READ'])
      await asignar(8, 1, 20, versionCentro)
      expect(await rolDe(8)).toBe(versionCentro)
    })

    it('el rol que estaba limitado a una sucursal ahora sirve a cualquier cuenta de la empresa', async () => {
      expect(await rolDe(9)).toBe(soloNorte)
      expect(await permisos(soloNorte)).toEqual(['EMPLEADOS_READ'])
      await asignar(8, 1, 10, soloNorte)
      await asignar(8, 1, null, soloNorte)
      expect(
        await one(
          'SELECT count(*)::int r FROM sgrh_usuarios_empresa_rol WHERE uer_usuario_id=8 AND uer_rol_id=$1',
          [soloNorte]
        )
      ).toBe(2)
    })
  })

  describe('aislamiento entre empresas', () => {
    it('editar el Gerente de una empresa no toca el de la otra ni la plantilla', async () => {
      const g1 = await rolId('EMPRESA_1_GERENTE')
      const antes = await permisos(g1)
      await save(A2, 2, await rolId('EMPRESA_2_GERENTE'), 'Gerente de Sucursal', [])
      expect(await permisos(await rolId('EMPRESA_2_GERENTE'))).toEqual([])
      expect(await permisos(g1)).toEqual(antes)
      expect(await permisos(4)).toEqual(['EMPLEADOS_READ', 'NOMINA_READ'])
    })

    it('una plantilla no se edita ni se elimina', async () => {
      await rejects(
        async () => save(A1, 1, 4, 'Gerente de Sucursal', []),
        /Rol no encontrado/,
        '42501'
      )
      await rejects(async () => remove(A1, 1, 4), /Rol no encontrado/, '42501')
      expect(await permisos(4)).toEqual(['EMPLEADOS_READ', 'NOMINA_READ'])
    })

    it('el rol de otra empresa no se edita ni se elimina', async () => {
      const ajeno = await rolId('EMPRESA_2_GERENTE')
      await rejects(async () => save(A1, 1, ajeno, 'Gerente', []), /Rol no encontrado/, '42501')
      await rejects(async () => remove(A1, 1, ajeno), /Rol no encontrado/, '42501')
    })

    it('un nombre igual en otra empresa no choca; en la misma sí', async () => {
      expect(await save(A1, 1, null, 'Cajero', [])).toBeGreaterThan(0)
      expect(await save(A2, 2, null, 'Cajero', [])).toBeGreaterThan(0)
      await rejects(async () => save(A1, 1, null, 'cajero ', []), /Ya existe un rol con ese nombre/)
    })
  })

  describe('permisos de quien administra', () => {
    it('sin ROLES_WRITE no se administra nada', async () => {
      await rejects(async () => save(G1, 1, null, 'Nuevo', []), /No tenés permiso/, '42501')
      await rejects(
        async () => remove(G1, 1, await rolId('EMPRESA_1_EMPLEADO')),
        /No tenés permiso/,
        '42501'
      )
    })

    it('no se otorga lo que el propio rol no tiene (MI_HORARIO_READ sí)', async () => {
      await actorRecortado(['ROLES_WRITE'])
      await rejects(
        async () => save(L1, 1, null, 'Con nómina', ['NOMINA_READ']),
        /que tu propio rol no tiene: NOMINA_READ/,
        '42501'
      )
      expect(await save(L1, 1, null, 'Con horario', ['MI_HORARIO_READ'])).toBeGreaterThan(0)
    })

    it('lo que el rol ya tenía se conserva aunque quien edita no lo tenga', async () => {
      await actorRecortado(['ROLES_WRITE'])
      const g = await rolId('EMPRESA_1_GERENTE')
      await save(L1, 1, g, 'Gerente de Sucursal', ['EMPLEADOS_READ', 'NOMINA_READ'])
      expect(await permisos(g)).toEqual(['EMPLEADOS_READ', 'NOMINA_READ'])
    })

    it('nadie le quita «Administrar roles» a su propio rol', async () => {
      await rejects(
        async () =>
          save(A1, 1, await rolId('EMPRESA_1_ADMIN'), 'Administrador de Empresa', ['NOMINA_READ']),
        /propio rol/,
        '23514'
      )
    })

    it('escribir exige poder ver, y el permiso del kiosco no se reparte', async () => {
      await rejects(
        async () => save(A1, 1, null, 'Sin ver', ['NOMINA_WRITE']),
        /NOMINA_WRITE requiere NOMINA_READ/,
        '23514'
      )
      await rejects(
        async () => save(A1, 1, null, 'Tablet', ['ASISTENCIA_KIOSCO']),
        /kiosco no se asigna/,
        '23514'
      )
    })
  })

  describe('eliminación', () => {
    it('un rol con usuarios activos no se elimina', async () => {
      // Cuenta asignaciones: el gerente de Norte y el que trabaja en dos tiendas (dos filas).
      await rejects(
        async () => remove(A1, 1, await rolId('EMPRESA_1_GERENTE')),
        /tiene 3 usuario\(s\) activo\(s\)/,
        '23514'
      )
    })

    it('sin asignaciones se borra; con asignaciones históricas se archiva', async () => {
      const libre = await save(A1, 1, null, 'Libre', ['EMPLEADOS_READ'])
      expect(await remove(A1, 1, libre)).toBe('eliminado')
      expect(await one('SELECT count(*)::int r FROM sgrh_cat_roles WHERE rol_id=$1', [libre])).toBe(
        0
      )

      const usado = await save(A1, 1, null, 'Usado', [])
      await asignar(8, 1, null, usado, false)
      expect(await remove(A1, 1, usado)).toBe('archivado')
      expect(await one('SELECT rol_activo r FROM sgrh_cat_roles WHERE rol_id=$1', [usado])).toBe(
        false
      )
      // Archivado deja libre el nombre y ya no se edita.
      expect(await save(A1, 1, null, 'Usado', [])).toBeGreaterThan(0)
      await rejects(async () => save(A1, 1, usado, 'Usado 2', []), /Rol no encontrado/, '42501')
    })
  })

  describe('trigger de asignación', () => {
    it('no se asigna una plantilla cuando la empresa tiene su copia', async () => {
      await rejects(async () => asignar(8, 1, null, 4), /propia copia de ese rol/, '23514')
      await rejects(
        async () =>
          db.query('UPDATE sgrh_usuarios_empresa_rol SET uer_rol_id=4 WHERE uer_usuario_id=4'),
        /propia copia/
      )
    })

    it('el rol del kiosco sí se asigna tal cual', async () => {
      await asignar(8, 1, 20, 13)
      expect(await rolDe(8)).toBe(13)
    })

    it('un rol de la empresa se asigna a cuentas de cualquier sucursal', async () => {
      const g = await rolId('EMPRESA_1_GERENTE')
      await asignar(8, 1, 10, g)
      await asignar(8, 1, 20, g)
      expect(await rolDe(8)).toBe(g)
    })

    it('rechaza roles de otra empresa o eliminados', async () => {
      const ajeno = await rolId('EMPRESA_2_GERENTE')
      await rejects(async () => asignar(8, 1, null, ajeno), /otra empresa/, '23514')
      const temporal = await save(A1, 1, null, 'Temporal', [])
      await asignar(8, 1, null, temporal, false)
      expect(await remove(A1, 1, temporal)).toBe('archivado')
      await rejects(async () => asignar(8, 1, null, temporal), /fue eliminado/, '23514')
    })
  })
})
