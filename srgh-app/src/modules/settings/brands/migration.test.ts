/**
 * Corre el SQL REAL de la migración de marcas (y las que necesita) sobre un
 * PostgreSQL desechable: nada de esto toca Supabase. Mismo enfoque que
 * branches/migration.test.ts.
 */
const actor = '00000000-0000-4000-8000-000000000001'
const outsider = '00000000-0000-4000-8000-000000000009'
let db: PGlite

const migration = (name: string) => readFileSync(resolve('supabase/migrations', name), 'utf8')

/**
 * Cada test corre en una transacción que se deshace al final. Un error
 * dentro de ella la abortaría entera, así que cada operación va en su propio
 * savepoint: si falla, se vuelve a él y el test puede seguir.
 */
async function safe<T>(fn: () => Promise<T>): Promise<T> {
  await db.exec('SAVEPOINT paso')
  try {
    const result = await fn()
    await db.exec('RELEASE SAVEPOINT paso')
    return result
  } catch (error) {
    await db.exec('ROLLBACK TO SAVEPOINT paso')
    throw error
  }
}

async function brand(id: number | null, data: object, company = 1, who = actor) {
  return safe(async () => {
    const r = await db.query<{ id: number }>(
      'SELECT public.sgrh_save_brand($1::uuid,$2,$3,$4::jsonb) id',
      [who, company, id, JSON.stringify(data)]
    )
    return r.rows[0].id
  })
}

async function eliminar(id: number, company = 1, who = actor) {
  return safe(async () => {
    const r = await db.query<{ logo: string | null }>(
      'SELECT public.sgrh_delete_brand($1::uuid,$2,$3) logo',
      [who, company, id]
    )
    return r.rows[0].logo
  })
}

async function existe(id: number) {
  const r = await db.query('SELECT 1 FROM sgrh_marcas_comerciales WHERE mco_id=$1', [id])
  return r.rows.length > 0
}

const branchData = {
  suc_nombre: 'Mall',
  suc_codigo_interno: '',
  suc_telefono: '',
  suc_email_sucursal: '',
  suc_latitud: null,
  suc_longitud: null,
  suc_radio_geocerca_metros: 50,
  suc_activa: true,
}
async function branch(id: number | null, data: object, company = 1) {
  return safe(async () => {
    const r = await db.query<{ id: number }>(
      'SELECT public.sgrh_save_branch($1::uuid,$2,$3,$4::jsonb,$5::jsonb) id',
      [
        actor,
        company,
        id,
        JSON.stringify(data),
        JSON.stringify({ dir_distrito_id: 1, dir_senas_exactas: 'Cien metros norte del parque' }),
      ]
    )
    return r.rows[0].id
  })
}
async function marcaDe(sucursal: number) {
  const r = await db.query<{ suc_marca_id: number | null }>(
    'SELECT suc_marca_id FROM sgrh_sucursales WHERE suc_id=$1',
    [sucursal]
  )
  return r.rows[0].suc_marca_id
}

